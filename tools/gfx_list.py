def fb(st):
    v = np.frombuffer(open('work/st/%s/vram.bin' % st, 'rb').read(), '<u2').reshape(512, 1024)[0:240, 0:320].astype(int)
    return Image.fromarray(np.stack([(v & 31) << 3, (v >> 5 & 31) << 3, (v >> 10 & 31) << 3], 2).astype(np.uint8))


